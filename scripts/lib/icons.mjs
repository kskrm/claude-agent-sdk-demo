export const ICON_NAMES = Object.keys(ICONS);

/**
 * 手描き風アイコンを返す。未知の名前は null（呼び出し側でアイコンを省く）。
 * @param {string} name アイコン名
 * @param {string} cls  付与するクラス名
 */
export function icon(name, cls = 'ic') {
  const d = ICONS[name];
  if (!d) return '';
  return `<svg class="${cls}" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="${d}" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" filter="url(#rough-soft)"/></svg>`;
}

/** 名前が使えるかどうか（apply-explain.mjs の検証用） */
export function isKnownIcon(name) {
  return typeof name === 'string' && Object.prototype.hasOwnProperty.call(ICONS, name);
}
